"""Build the app's fast photo-native module (fm-3xjm) from the pinned toolchain and sources.

Same dlib 20.0.1 / Pillow 12.3.0 / libjpeg-turbo 3.1.4.1 sources and Emscripten 4.0.23 as classic
photo-runtime/build.py, with three changes that leave every landmark and prepared byte unchanged
(photo/native/native.test.mjs holds it equal to the pinned runtime build):
  - -O3 -msimd128 and native WebAssembly exceptions (-fwasm-exceptions) instead of -O2 and
    JavaScript-emulated exceptions, which routed every call inside a try block through JS;
  - the landmark model is read by a direct parser of dlib's serialization format (same checks,
    member-for-member identical, falls back to dlib::deserialize on anything unexpected);
  - the edge-padding Gaussian blur precomputes its reflected rows/columns and keeps each output's
    accumulation order.
The selection worker falls back to the pinned manifest build when this module does not compile
(no SIMD or wasm exceptions). Run bootstrap.py once, then this; sources and objects stay in the work directory
(PHOTO_NATIVE_WORK, default ~/.cache/facemorph-photo-native) and outputs go to src/Next/photo/native/.
"""
from pathlib import Path
import hashlib, json, os, subprocess
C = Path(__file__).resolve().parent
W = Path(os.environ.get('PHOTO_NATIVE_WORK', Path.home()/'.cache/facemorph-photo-native'))
SDK = W/'emsdk/upstream/emscripten'
P = W/'vendor/pillow-12.3.0/src/libImaging'
D = W/'vendor/dlib-20.0.1'
J = W/'vendor/libjpeg-turbo-3.1.4.1'; JB = W/'jpeg-build'
OUT = C.parent/'src/Next/photo/native'; OUT.mkdir(exist_ok=True)
O = W/'obj'; O.mkdir(parents=True, exist_ok=True)
H = W/'pillow-cxx-header'; H.mkdir(exist_ok=True)
# Pillow's C-only struct tag and pointer typedef use the same identifier, which
# is illegal in C++. Rename only the unused arena struct tag in this header view.
(H/'Imaging.h').write_text((P/'Imaging.h').read_text().replace('struct ImagingMemoryArena', 'struct ImagingMemoryArenaStorage'))
env = dict(os.environ, EMCC_CORES=os.environ.get('EMCC_CORES', '4'))
subprocess.run([str(SDK/'emcmake'), 'cmake', '-S', str(J), '-B', str(JB), '-DCMAKE_BUILD_TYPE=Release', '-DENABLE_SHARED=OFF', '-DENABLE_STATIC=ON', '-DWITH_SIMD=OFF', '-DWITH_TURBOJPEG=OFF', '-DWITH_TOOLS=OFF', '-DWITH_TESTS=OFF'], check=True, env=env)
subprocess.run(['cmake', '--build', str(JB), '--target', 'jpeg-static', '-j', '4'], check=True, env=env)
# -ffp-contract=off as classic: no fused multiply-add, so float results match the reference.
flags = ['-O3', '-msimd128', '-fwasm-exceptions', '-ffp-contract=off', '-ffunction-sections', '-fdata-sections', '-ffile-prefix-map='+str(W)+'=work', '-ffile-prefix-map='+str(C)+'=.', '-I'+str(C/'native'), '-I'+str(H), '-I'+str(P)]
objects = []
for path in [C/'native/pillow_support.c', P/'Geometry.c', P/'Resample.c']:
    target = O/(path.stem+'.o'); subprocess.run([str(SDK/'emcc'), *flags, '-c', str(path), '-o', str(target)], check=True, env=env); objects.append(str(target))
cxx = [str(SDK/'em++'), *flags, '-std=c++17', '-DDLIB_NO_GUI_SUPPORT', '-DDLIB_PNG_SUPPORT', '-DDLIB_JPEG_SUPPORT', '-I'+str(D), '-I'+str(J/'src'), '-I'+str(JB), '-sUSE_LIBPNG=1']
for path in [C/'native/photo.cpp', D/'dlib/all/source.cpp']:
    target = O/(path.stem+'.o'); subprocess.run([*cxx, '-c', str(path), '-o', str(target)], check=True, env=env); objects.append(str(target))
command = [*cxx, *objects, str(JB/'libjpeg.a'), '-sMODULARIZE=1', '-sEXPORT_ES6=1', '-sEXPORT_NAME=createPhotoModule', '-sENVIRONMENT=web,worker,node', '-sFILESYSTEM=0', '-sALLOW_MEMORY_GROWTH=1', '-sINITIAL_MEMORY=33554432', '-sMAXIMUM_MEMORY=268435456', '-sSTACK_SIZE=2097152', '-sABORTING_MALLOC=0', '-sMALLOC=emmalloc', '-sEXPORTED_FUNCTIONS=["_malloc","_free"]', '-sEXPORTED_RUNTIME_METHODS=["UTF8ToString","HEAPU8"]', '-o', str(OUT/'photo-native.mjs')]
subprocess.run(command, check=True, env=env)
digest = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
files = {str(p.relative_to(C.parent)): {'sha256': digest(p), 'bytes': p.stat().st_size} for p in sorted((C/'native').glob('*'))+[OUT/'photo-native.mjs', OUT/'photo-native.wasm']}
(OUT/'build-receipt.json').write_text(json.dumps({'compiler': 'Emscripten4.0.23', 'dlib': '20.0.1', 'pillow': '12.3.0', 'jpeg': 'libjpeg-turbo3.1.4.1', 'flags': flags[:3], 'maxWasmBytes': 268435456, 'unshared': True, 'files': files}, indent=2)+'\n')
glue, wasm = OUT/'photo-native.mjs', OUT/'photo-native.wasm'
(OUT/'identity.mjs').write_text('// Generated by apps/web/photo-native/build.py: the fast build the selection worker verifies before use.\n'
    f"export const FAST_NATIVE=Object.freeze({{glue:{{sha256:'{digest(glue)}',size:{glue.stat().st_size}}},wasm:{{sha256:'{digest(wasm)}',size:{wasm.stat().st_size}}}}});\n")
print(json.dumps(files, indent=2))
