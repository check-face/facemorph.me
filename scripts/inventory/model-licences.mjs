#!/usr/bin/env node
// Model licence links from import/licences.json (fm-qoc3). Each row's `notices` names the licence texts published
// beside the weights at /runtime/notices/ (hosting/next-static/stage.py stages hosting/next/notices/ there). From
// those rows this writes, so the copies never drift from the record:
//   - apps/web/shell/render/model-licences.ts   the app's FAQ entry and download-consent links
//   - hosting/next/notices/index.html           the notices page's model list (between model-licences markers)
//   - the package READMEs and the quickstart     a "model terms" list (between model-terms markers)
// --check writes nothing and exits 1 when any output differs from what the rows give.
//   node scripts/inventory/model-licences.mjs [--check]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LICENCES, REPO, line, options, readJson } from './lib.mjs';

export const NOTICES_DIR = 'hosting/next/notices/';
/** Where stage.py publishes NOTICES_DIR. */
export const SERVED = '/runtime/notices/';
export const MODULE = 'apps/web/shell/render/model-licences.ts';
export const INDEX = 'hosting/next/notices/index.html';
export const READMES = [
  'packages/stylegan-js/README.md',
  'packages/browser-model-manager/README.md',
  'packages/cloudflare-model-host/README.md',
  'docs/dev/build-next.md',
];
const HTML_MARK = ['<!-- model-licences:start -->', '<!-- model-licences:end -->'];
const MD_MARK = ['<!-- model-terms:start -->', '<!-- model-terms:end -->'];

/** Every notice of every row, in row order: {row, file, title, upstream, href}. Pure. */
export function modelNotices(rows) {
  return rows.flatMap((r) =>
    (r.notices ?? []).map((n) => ({
      row: r.id,
      file: n.file,
      title: n.title,
      upstream: n.upstream,
      href: SERVED + basename(n.file) + (n.fragment ? `#${n.fragment}` : ''),
    })),
  );
}

/** Problems with the rows' notices: a file outside NOTICES_DIR, a missing title/upstream, a notice_file that is
 * not one of the row's notices. Pure. */
export function noticeProblems(rows) {
  const out = [];
  for (const r of rows) {
    if (!r.notices) continue;
    for (const n of r.notices) {
      if (!n.file?.startsWith(NOTICES_DIR) || n.file.slice(NOTICES_DIR.length).includes('/'))
        out.push({ row: r.id, problem: `notice ${n.file} is not in ${NOTICES_DIR}` });
      if (!n.title || !(n.upstream ?? '').startsWith('https://'))
        out.push({ row: r.id, problem: `notice ${n.file} needs a title and an https upstream` });
    }
    if (r.notice_file && !r.notices.some((n) => n.file === r.notice_file))
      out.push({ row: r.id, problem: `notice_file ${r.notice_file} is not among its notices` });
  }
  return out;
}

const escapeHtml = (s) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export function moduleText(notices) {
  const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  const links = notices
    .map((n) => `  {\n    title: ${q(n.title)},\n    href: ${q(n.href)},\n  },\n`)
    .join('');
  return `// Generated by scripts/inventory/model-licences.mjs from import/licences.json rows' \`notices\`; do not edit.
// Each model licence text, as published beside the weights at ${SERVED} (fm-qoc3).

export interface ModelLicence {
  readonly title: string;
  readonly href: string;
}

export const MODEL_LICENCES: readonly ModelLicence[] = [
${links}];
`;
}

/** The notices page's own model list: every notice except the ones on the page itself. */
export function indexList(notices) {
  const own = basename(INDEX);
  const items = notices
    .filter((n) => basename(n.file) !== own)
    .map((n) => `<li><a href="${basename(n.file)}">${escapeHtml(n.title)}</a></li>`)
    .join('');
  return `<ul>${items}</ul>`;
}

export function readmeList(notices) {
  return notices
    .map(
      (n) =>
        `- ${n.title}: [upstream text](${n.upstream}); served beside the weights as \`notices/${basename(n.file)}${n.href.includes('#') ? '#' + n.href.split('#')[1] : ''}\``,
    )
    .join('\n');
}

/** `text` with the content between `marks` replaced by `inner`; throws when the markers are missing. Pure. */
export function splice(text, [start, end], inner, sep = '') {
  const a = text.indexOf(start);
  const b = text.indexOf(end);
  if (a < 0 || b < a) throw Error(`missing ${start} … ${end}`);
  return text.slice(0, a + start.length) + sep + inner + sep + text.slice(b);
}

/** {path: expected text} for every generated output. */
export function outputs(rows, read = (p) => readFileSync(join(REPO, p), 'utf8')) {
  const notices = modelNotices(rows);
  const out = {
    [MODULE]: moduleText(notices),
    [INDEX]: splice(read(INDEX), HTML_MARK, indexList(notices)),
  };
  for (const p of READMES) out[p] = splice(read(p), MD_MARK, readmeList(notices), '\n');
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const opts = options(process.argv.slice(2));
  const { rows } = readJson(LICENCES);
  const findings = noticeProblems(rows);
  for (const n of modelNotices(rows))
    if (!existsSync(join(REPO, n.file)))
      findings.push({ row: n.row, problem: `notice ${n.file} does not exist` });
  const expected = outputs(rows);
  for (const [path, text] of Object.entries(expected)) {
    const now = existsSync(join(REPO, path)) ? readFileSync(join(REPO, path), 'utf8') : null;
    if (now === text) continue;
    if (opts.check)
      findings.push({ path, problem: 'differs from import/licences.json (run without --check)' });
    else {
      writeFileSync(join(REPO, path), text);
      line({ wrote: path });
    }
  }
  for (const f of findings) line(f);
  line({ summary: { ok: !findings.length, findings: findings.length } });
  process.exit(findings.length ? 1 : 0);
}
