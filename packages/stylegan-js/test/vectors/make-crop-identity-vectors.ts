// Regenerates confirmed-crop-identity.json: records differing in one field each, plus one with
// reordered keys. Expected identities come from node:crypto over the canonical JSON, a reference
// independent of the package's own SHA-256.
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { canonicalJson, CROP_PREPROCESSING_POLICY_V1 } from '../../src/index.ts';

const base = {
  sourceRevision: 3,
  sourceDigest: 'a'.repeat(64),
  rect: { left: 120, top: 40, width: 800, height: 800 },
  rotationDegrees: 0,
  exifOrientation: 1,
  exifApplied: false,
  policyVersion: 'crop-preprocessing-v1',
  policyParams: CROP_PREPROCESSING_POLICY_V1,
};
const variants: [string, object][] = [
  ['base', base],
  ['sourceRevision', { ...base, sourceRevision: 4 }],
  ['sourceDigest', { ...base, sourceDigest: 'b'.repeat(64) }],
  ['rect', { ...base, rect: { ...base.rect, left: 121 } }],
  ['rotationDegrees', { ...base, rotationDegrees: 90 }],
  ['exifOrientation', { ...base, exifOrientation: 6 }],
  ['exifApplied', { ...base, exifApplied: true }],
];
const reordered = Object.fromEntries(Object.entries(base).reverse());
const id = (r: object) => createHash('sha256').update(canonicalJson(r), 'utf8').digest('hex');
const vectors = {
  note: 'Generated by make-crop-identity-vectors.ts; identities are node:crypto SHA-256 of canonical JSON.',
  baseCanonical: canonicalJson(base),
  records: variants.map(([changed, record]) => ({ changed, record, confirmedCropId: id(record) })),
  reordered: { record: reordered, confirmedCropId: id(base) },
};
writeFileSync(new URL('./confirmed-crop-identity.json', import.meta.url), JSON.stringify(vectors, null, 2) + '\n');
